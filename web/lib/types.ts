export const shortDate = (v?: string | null) =>
  v ? v.slice(0, 10).replaceAll("-", ".") : "未公布";
export const shortTime = (v?: string | null) =>
  v ? v.slice(0, 16).replace("T", " ").replaceAll("-", ".") : "尚无记录";
